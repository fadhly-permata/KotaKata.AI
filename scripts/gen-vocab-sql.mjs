// Builds supabase/vocabulary.sql from src/data/vocabulary/tierN*.ts
// (1000 kata/tier, semua kata asli KBBI — lihat scripts/build-kbbi-seed.mjs).
// Validates: exactly 1000 words per tier, no duplicate words, no duplicate ids.
// Usage:
//   node scripts/gen-vocab-sql.mjs          # semua tier (1..10)
//   node scripts/gen-vocab-sql.mjs 4        # hanya tier 1..4
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const vocabDir = join(ROOT, "src", "data", "vocabulary");
const outPath = join(ROOT, "supabase", "vocabulary.sql");

// Setiap tier: 1000 kata
const WORDS_PER_TIER = 1000;
// Argumen opsional: batas tier tertinggi yang disertakan (mis. "4" => tier 1..4)
const maxTier = process.argv[2] ? Number(process.argv[2]) : Infinity;

const esc = (s) => `'${s.replace(/'/g, "''").replace(/\"/g, '\\"')}'`;

// ---- Collect items: { word_id, word, clue_1, clue_2, clue_3, tier_level } ----
const items = [];
const errors = [];

// Cocokkan file tier: tier1.ts..tier10.ts, tierNa.ts/tierNb.ts, dan part
// (mis. tier4-part1.ts) — part file ikut dibaca agar aggregator tier4.ts
// (yang hanya import + spread) tetap menghasilkan 1000 kata utuh.
const tierFiles = readdirSync(vocabDir)
  .filter((f) => /^tier(\d+)(?:[ab]|-part\d+)?\.ts$/.test(f))
  .sort();
const byTier = new Map();
for (const f of tierFiles) {
  const m = f.match(/^tier(\d+)/);
  const tier = Number(m[1]);
  if (tier > maxTier) continue;
  const src = readFileSync(join(vocabDir, f), "utf8");
  const tuples = [...src.matchAll(/^  \["([^"]+)",\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\],$/gm)].map(
    (mm) => [mm[1], mm[2], mm[3], mm[4]],
  );
  byTier.set(tier, [...(byTier.get(tier) ?? []), ...tuples]);
}

for (const [tier, tuples] of [...byTier.entries()].sort((a, b) => a[0] - b[0])) {
  if (tuples.length < WORDS_PER_TIER) {
    errors.push(`tier${tier}: KURANG — punya ${tuples.length} kata, harus minimal ${WORDS_PER_TIER}`);
  }
  const selected = tuples.slice(0, WORDS_PER_TIER);
  selected.forEach(([word, clue_1, clue_2, clue_3], i) => {
    items.push({
      word_id: `t${tier}-${String(i + 1).padStart(3, "0")}`,
      word,
      clue_1,
      clue_2,
      clue_3,
      tier_level: tier,
    });
  });
}

// ---- Dedup (keep first occurrence) + validate ----
const dropped = [];
const seenWords = new Set();
const seenIds = new Set();
const deduped = [];
for (const it of items) {
  if (seenWords.has(it.word)) {
    dropped.push(it.word);
    continue;
  }
  seenWords.add(it.word);
  if (seenIds.has(it.word_id)) errors.push(`duplikat id: ${it.word_id}`);
  seenIds.add(it.word_id);
  deduped.push(it);
}
items.length = 0;
items.push(...deduped);

if (dropped.length) console.warn(`DEDUP: ${dropped.length} kata duplikat dibuang → ${dropped.slice(0, 10).join(", ")}${dropped.length > 10 ? " …" : ""}`);

if (errors.length) {
  console.error("VALIDASI GAGAL:");
  errors.slice(0, 40).forEach((e) => console.error("  -", e));
  console.error(`total: ${errors.length} error`);
  process.exit(1);
}

// ---- Emit SQL ----
const byTierOut = new Map();
for (const it of items) {
  byTierOut.set(it.tier_level, (byTierOut.get(it.tier_level) ?? 0) + 1);
}
const tierSummary = [...byTierOut.entries()].sort((a, b) => a[0] - b[0]).map(([t, n]) => `t${t}:${n}`).join(" ");

const rows = items.map(
  (it) => `  (${esc(it.word_id)}, ${esc(it.word)}, ${esc(it.clue_1)}, ${esc(it.clue_2)}, ${esc(it.clue_3)}, ${it.tier_level})`,
);

const out = `-- ============================================================
-- KotaKata AI — Vocabulary (soal / pertanyaan)
-- Generated by scripts/gen-vocab-sql.mjs — DO NOT EDIT BY HAND
-- Sumber data: KBBI (Kamus Besar Bahasa Indonesia) — build-kbbi-seed.mjs
-- Total: ${items.length} words | per tier: ${tierSummary}
-- ============================================================

create table if not exists public.vocabulary (
  word_id    text primary key,
  word       text not null,
  clue_1     text not null,
  clue_2     text,
  clue_3     text,
  tier_level int  not null default 1,
  created_at timestamptz not null default now()
);

-- Isi tabel DIBERSIHKAN tiap generate (data soal dikelola dari repo).
-- CASCADE: word_discoveries punya FK ON DELETE CASCADE ke vocabulary, jadi
-- TRUNCATE biasa ditolak Postgres. Catatan: cascade ikut menghapus riwayat
-- penemuan — untuk seed ulang non-destruktif nanti gunakan upsert (on conflict).
truncate table public.vocabulary cascade;

insert into public.vocabulary (word_id, word, clue_1, clue_2, clue_3, tier_level) values
${rows.join(",\n")}
on conflict (word_id) do nothing;

create index if not exists idx_vocabulary_tier on public.vocabulary (tier_level);
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out);
console.log(`OK — ${items.length} words → ${outPath}`);
console.log(`Per tier: ${tierSummary}`);
